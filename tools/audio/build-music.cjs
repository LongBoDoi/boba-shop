/* Split the requested Dan Musselman video at its published chapter boundaries.
 * Usage: node tools/audio/build-music.cjs <downloaded-audio> [yt-dlp-info.json]
 * Requires ffmpeg on PATH or FFMPEG_PATH. Source downloads/tools stay outside the app.
 */
const fs = require('node:fs');
const path = require('node:path');
const cp = require('node:child_process');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '../..');
const input = process.argv[2];
if (!input || !fs.existsSync(input)) throw Error('Pass the downloaded source audio file');
const manifestFile = path.join(__dirname, 'music-source.json');
const hash = (file) => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
let manifest;
if (process.argv[3]) {
  const info = JSON.parse(fs.readFileSync(process.argv[3], 'utf8'));
  if (info.id !== 'rCHMqrkoyFA' || info.chapters?.length !== 30) throw Error('Unexpected source or chapters');
  manifest = {
    video: 'https://www.youtube.com/watch?v=rCHMqrkoyFA',
    title: info.title, artist: 'Dan Musselman', duration: info.duration,
    sourceSha256: hash(input),
    // The video does not declare a free-content licence. This is not part of the CC0 Foley bank.
    license: 'Copyright Dan Musselman; no open-content license declared in the source video',
    tracks: info.chapters.map((chapter, i) => ({
      id: chapter.title.replace(/^\d+\.\./, '').normalize('NFKD').replace(/[^\w\s-]/g, '').trim().toLowerCase().replace(/\s+/g, '-'),
      number: i + 1, title: chapter.title.replace(/^\d+\.\./, ''),
      start: chapter.start_time, end: chapter.end_time,
    })),
  };
} else {
  manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
  if (hash(input) !== manifest.sourceSha256) throw Error('Source audio checksum differs from the edit manifest');
}
const out = path.join(root, 'src/assets/audio/music');
fs.mkdirSync(out, { recursive: true });
const ffmpeg = process.env.FFMPEG_PATH || 'ffmpeg';
for (const track of manifest.tracks) {
  const duration = track.end - track.start;
  const file = path.join(out, `${track.id}.m4a`);
  // Keep the performance and dynamics. Very short edge ramps only prevent a cut from clicking.
  cp.execFileSync(ffmpeg, ['-y', '-v', 'error', '-ss', String(track.start), '-i', input,
    '-t', String(duration), '-vn', '-map_metadata', '-1', '-ac', '2', '-ar', '44100',
    '-af', `afade=t=in:d=0.015,afade=t=out:st=${duration - 0.04}:d=0.04`,
    '-c:a', 'aac', '-b:a', '96k', '-movflags', '+faststart',
    '-metadata', `title=${track.title}`, '-metadata', `artist=${manifest.artist}`, file]);
  track.bytes = fs.statSync(file).size;
  track.sha256 = hash(file);
  console.log(`${track.number}. ${track.title} (${duration}s)`);
}
fs.writeFileSync(manifestFile, JSON.stringify(manifest, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'src/game/music.ts'),
  '// Generated chapter catalogue. No browser APIs or asset imports: safe in saves and Node checks.\n'
  + 'export const MUSIC_TRACKS = ' + JSON.stringify(manifest.tracks.map(({ id, number, title, start, end }) => ({ id, number, title, start, duration: end - start })), null, 2)
  + ' as const;\n\nexport type MusicTrackId = typeof MUSIC_TRACKS[number][\'id\'];\n'
  + "export type MusicChoice = MusicTrackId | 'cycle' | 'shuffle';\n"
  + "export function isMusicChoice(value: unknown): value is MusicChoice {\n"
  + "  return value === 'cycle' || value === 'shuffle' || MUSIC_TRACKS.some((track) => track.id === value);\n}\n");
fs.writeFileSync(path.join(root, 'src/audio/musicAssets.ts'),
  '// Generated by tools/audio/build-music.cjs. Loaded one track at a time, outside effect warmup.\n'
  + "import type { MusicTrackId } from '../game/music';\n"
  + manifest.tracks.map((t, i) => `import track${i + 1} from '../assets/audio/music/${t.id}.m4a';`).join('\n')
  + '\nexport const MUSIC_ASSETS: Record<MusicTrackId, string> = {\n'
  + manifest.tracks.map((t, i) => `  '${t.id}': track${i + 1},`).join('\n') + '\n};\n');
fs.writeFileSync(path.join(out, 'CREDITS.md'),
  `# Background music\n\n**${manifest.title}** — composed and recorded by **${manifest.artist}**.\n\n`
  + `Source: [original video](${manifest.video}). The 30 tracks follow the timestamps published by the artist.\n\n`
  + 'These recordings are copyrighted and are **not** covered by the CC0 licence of the game’s Foley effects. '
  + 'The source video does not declare an open-content licence. Inclusion here does not grant redistribution rights; '
  + 'permission for use and distribution must come from the rights holder.\n\n'
  + '| # | Track | Start | Duration |\n|---|---|---|---|\n'
  + manifest.tracks.map((t) => `| ${t.number} | ${t.title} | ${t.start}s | ${t.end - t.start}s |`).join('\n') + '\n');
console.log(`${manifest.tracks.length} tracks, ${Math.round(manifest.tracks.reduce((n, t) => n + t.bytes, 0) / 1024 / 1024)} MB`);
