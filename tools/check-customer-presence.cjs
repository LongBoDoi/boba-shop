/* RAW reducer: no headless/instant-arrival adapter. Travel may take arbitrarily long. */
const assert = require('node:assert/strict');
const { src } = require('./sim/load.cjs');
const { createInitialState, gameReducer: R, frontSlot, patienceLeft, canServe } = src('game/reducer.ts');
const { parseGame, serializeGame } = src('game/save.ts');
const open = () => R(createInitialState(782), { type: 'START_DAY', day: 30 });
let state = open();
for (let i=0;i<180 && (state.slots.some(c=>!c)||state.waveLeft>0);i++) state=R(state,{type:'TICK',dt:100});
const slot=frontSlot(state.slots), id=state.slots[slot].id;
assert(state.line.length>0);
assert(state.slots.filter(Boolean).every(c=>c.atCounter===false));
assert.equal(R(state,{type:'TAKE_ORDER',slot}),state,'Cannot order while walking');
assert.equal(R(state,{type:'CUSTOMER_AT_COUNTER',id:999999}),state,'Stale arrival does nothing');
const rear=state.slots.find(c=>c&&c.id!==id);
assert.equal(R(state,{type:'CUSTOMER_AT_COUNTER',id:rear.id}),state,'Only the front guest can begin service');
const beforeIds=[...state.slots,...state.line].filter(Boolean).map(c=>c.id);
state=R(state,{type:'TICK',dt:300000});
assert.deepEqual([...state.slots,...state.line].filter(Boolean).map(c=>c.id),beforeIds,'Nobody disappears while outside or advancing');
assert.equal(state.stats.missed,0); assert.equal(state.lost,0); assert.equal(state.departures.length,0);
for(const c of [...state.slots,...state.line].filter(Boolean))assert.equal(patienceLeft(c,state.clock),1);
const saved=parseGame(serializeGame(state));
assert(saved&&saved.slots[slot].atCounter===false,'A save cannot turn an approaching guest into an arrived one');
state=R(R(saved,{type:'SET_PAUSED',paused:false}),{type:'CUSTOMER_AT_COUNTER',id});
assert.equal(state.slots[slot].arrivedAt,state.clock);
assert.equal(state.slots[slot].status,'requesting');
assert.equal(patienceLeft(state.slots[slot],state.clock),1);
state=R(state,{type:'TICK',dt:1000});
assert(patienceLeft(state.slots[slot],state.clock)<1);
assert.equal(R(state,{type:'CUSTOMER_AT_COUNTER',id}),state,'Repeated arrival must not refill patience');
state=R(state,{type:'TAKE_ORDER',slot});
assert.equal(state.slots[slot].orderedAt,state.clock);
assert.equal(patienceLeft(state.slots[slot],state.clock),1,'Taking the order starts the separate preparation timer');
const ready={...state,cup:state.slots[slot].order,build:{...state.build,fill:.65,lidded:true,straw:true,atCounter:true}};
assert(canServe(ready));
assert(!canServe({...ready,slots:ready.slots.map((c,i)=>i===slot?{...c,atCounter:false}:c)}));
let following=R(ready,{type:'SERVE'});
const followingSlot=frontSlot(following.slots), followingId=following.slots[followingSlot].id;
assert.equal(following.slots[followingSlot].atCounter,false);
following=R(following,{type:'TICK',dt:120000});
assert.equal(following.slots[followingSlot].id,followingId,'Advancing after service cannot expire the next guest');
assert.equal(patienceLeft(following.slots[followingSlot],following.clock),1);
following=R(following,{type:'CUSTOMER_AT_COUNTER',id:followingId});
assert.equal(following.slots[followingSlot].arrivedAt,following.clock);
for(const extra of [{mode:'relaxed'},{gear:['board']}]){
 let auto={...open(),...extra};auto=R(auto,{type:'TICK',dt:5000});const head=frontSlot(auto.slots);
 assert.equal(auto.slots[head].status,'requesting','Auto-order must wait for physical arrival');
 auto=R(auto,{type:'CUSTOMER_AT_COUNTER',id:auto.slots[head].id});
 assert.equal(auto.slots[head].status,'ordered');assert.equal(auto.slots[head].orderedAt,auto.clock);
}
let mixed=R(open(),{type:'TICK',dt:5000});mixed=R(mixed,{type:'SET_MODE',mode:'relaxed'});
assert(mixed.slots.filter(Boolean).every(c=>c.status==='requesting'),'Changing mode cannot order for a moving customer');
const invalid=JSON.parse(serializeGame(mixed));invalid.slots.find(Boolean).atCounter='yes';
assert.equal(parseGame(JSON.stringify(invalid)),null,'Invalid presence flags are rejected');
console.log('check-customer-presence: no walking/outside timers, physical arrival gate, auto-orders, saves, duplicate callbacks and service timers passed');
